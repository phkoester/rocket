/*
 * test-int128.cc
 */

#include "rocket-test/rocket-test.h"

#include <limits>

namespace {

// Constants ------------------------------------------------------------------------------------------------

constexpr i128 I128_MIN = numeric_limits<i128>::min();
constexpr i128 I128_MAX = numeric_limits<i128>::max();
constexpr u128 U128_MAX = numeric_limits<u128>::max();

/// 2^64 - 1, the largest value that fits into the low half.
constexpr u128 U64_MAX = 0xFFFF'FFFF'FFFF'FFFF_u128;
/// 2^64, the smallest value that needs the high half.
constexpr u128 TWO_64 = 0x1'0000'0000'0000'0000_u128;

/// A value with distinct bits in both halves.
constexpr u128 PATTERN = 0x0123'4567'89AB'CDEF'FEDC'BA98'7654'3210_u128;

} // namespace

// `TEST` ---------------------------------------------------------------------------------------------------

TEST(int128, limits) {
  EXPECT_EQ(I128_MAX, 170141183460469231731687303715884105727_i128);
  EXPECT_EQ(U128_MAX, 340282366920938463463374607431768211455_u128);
  EXPECT_EQ(U128_MAX, 0xFFFF'FFFF'FFFF'FFFF'FFFF'FFFF'FFFF'FFFF_u128);
  EXPECT_EQ(I128_MIN, -I128_MAX - 1_i128);
  EXPECT_EQ(u128(-1), U128_MAX);
}

TEST(int128, opCmp) {
  EXPECT_LT(i128(-1), i128(0));
  EXPECT_GT(u128(-1), u128(0));

  EXPECT_LT(I128_MIN, -1_i128);
  EXPECT_LT(1_i128, I128_MAX);
  EXPECT_LT(U64_MAX, TWO_64);
  EXPECT_GT(TWO_64, U64_MAX);
  EXPECT_LE(TWO_64, TWO_64);
  EXPECT_GE(TWO_64, TWO_64);
  EXPECT_NE(TWO_64, U64_MAX);
  // The high half dominates
  EXPECT_LT(0x1'0000'0000'0000'0000_u128, 0x1'0000'0000'0000'0001_u128);
  EXPECT_LT(0x0'FFFF'FFFF'FFFF'FFFF_u128, 0x1'0000'0000'0000'0000_u128);
}

TEST(int128, opNeg) {
  EXPECT_EQ(-(1_i128), i128(-1));
  EXPECT_EQ(-(-42_i128), 42_i128);
  EXPECT_EQ(-I128_MAX, I128_MIN + 1_i128);
  EXPECT_EQ(-i128(TWO_64), -18446744073709551616_i128);

  // Unsigned negation wraps
  EXPECT_EQ(-(1_u128), U128_MAX);
  EXPECT_EQ(-TWO_64, 0xFFFF'FFFF'FFFF'FFFF'0000'0000'0000'0000_u128);
}

TEST(int128, opAdd) {
  // Signed
  EXPECT_EQ(1_i128 + 2_i128, 3_i128);
  EXPECT_EQ(-1_i128 + 1_i128, 0_i128);
  EXPECT_EQ(-5_i128 + 3_i128, -2_i128);
  EXPECT_EQ(-5_i128 + -3_i128, -8_i128);
  EXPECT_EQ(I128_MIN + I128_MAX, -1_i128);
  EXPECT_EQ(I128_MAX + -1_i128, 170141183460469231731687303715884105726_i128);
  EXPECT_EQ(100000000000000000000_i128 + 100000000000000000000_i128, 200000000000000000000_i128);

  // Unsigned, carry from the low into the high half
  EXPECT_EQ(U64_MAX + 1_u128, TWO_64);
  EXPECT_EQ(TWO_64 + TWO_64, 0x2'0000'0000'0000'0000_u128);
  EXPECT_EQ(PATTERN + 0xFEDC'BA98'7654'3210'0123'4567'89AB'CDEF_u128, U128_MAX);

  // Unsigned wraps
  EXPECT_EQ(U128_MAX + 1_u128, 0_u128);
  EXPECT_EQ(U128_MAX + U128_MAX, U128_MAX - 1_u128);

  // Compound
  i128 a = -10_i128;
  a += 25_i128;
  EXPECT_EQ(a, 15_i128);
  u128 b = U64_MAX;
  b += U64_MAX;
  EXPECT_EQ(b, 0x1'FFFF'FFFF'FFFF'FFFE_u128);
}

TEST(int128, opSub) {
  // Signed
  EXPECT_EQ(3_i128 - 2_i128, 1_i128);
  EXPECT_EQ(2_i128 - 3_i128, -1_i128);
  EXPECT_EQ(-5_i128 - 3_i128, -8_i128);
  EXPECT_EQ(-5_i128 - -3_i128, -2_i128);
  EXPECT_EQ(I128_MIN - -1_i128, I128_MIN + 1_i128);
  EXPECT_EQ(I128_MAX - I128_MAX, 0_i128);
  EXPECT_EQ(-1_i128 - I128_MAX, I128_MIN);

  // Unsigned, borrow from the high into the low half
  EXPECT_EQ(TWO_64 - 1_u128, U64_MAX);
  EXPECT_EQ(U128_MAX - PATTERN, 0xFEDC'BA98'7654'3210'0123'4567'89AB'CDEF_u128);

  // Unsigned wraps
  EXPECT_EQ(0_u128 - 1_u128, U128_MAX);
  EXPECT_EQ(U64_MAX - TWO_64, U128_MAX);

  // Compound
  i128 a = 10_i128;
  a -= 25_i128;
  EXPECT_EQ(a, -15_i128);
  u128 b = TWO_64;
  b -= U64_MAX;
  EXPECT_EQ(b, 1_u128);
}

TEST(int128, opMul) {
  // Signed
  EXPECT_EQ(6_i128 * 7_i128, 42_i128);
  EXPECT_EQ(-6_i128 * 7_i128, -42_i128);
  EXPECT_EQ(6_i128 * -7_i128, -42_i128);
  EXPECT_EQ(-6_i128 * -7_i128, 42_i128);
  EXPECT_EQ(0_i128 * I128_MIN, 0_i128);
  EXPECT_EQ(I128_MAX * 1_i128, I128_MAX);
  EXPECT_EQ(I128_MAX * -1_i128, I128_MIN + 1_i128);
  EXPECT_EQ(
    100000000000000000000_i128 * 1000000000000000000_i128,
    100000000000000000000000000000000000000_i128);
  EXPECT_EQ(
    -100000000000000000000_i128 * 1000000000000000000_i128,
    -100000000000000000000000000000000000000_i128);

  // Unsigned, the product spans both halves
  EXPECT_EQ(U64_MAX * U64_MAX, 0xFFFF'FFFF'FFFF'FFFE'0000'0000'0000'0001_u128);
  EXPECT_EQ(TWO_64 * TWO_64, 0_u128); // 2^128 wraps to 0
  EXPECT_EQ(PATTERN * 3_u128, 0x0369'D036'9D03'69CF'FC96'2FC9'62FC'9630_u128);
  EXPECT_EQ(PATTERN * 0x10_u128, 0x1234'5678'9ABC'DEFF'EDCB'A987'6543'2100_u128);

  // Unsigned wraps
  EXPECT_EQ(U128_MAX * U128_MAX, 1_u128);
  EXPECT_EQ(U128_MAX * 2_u128, U128_MAX - 1_u128);

  // Compound
  i128 a = -3_i128;
  a *= 1000000000000000000000_i128;
  EXPECT_EQ(a, -3000000000000000000000_i128);
  u128 b = TWO_64;
  b *= 3_u128;
  EXPECT_EQ(b, 0x3'0000'0000'0000'0000_u128);
}

TEST(int128, opDiv) {
  // Signed, truncates toward zero
  EXPECT_EQ(42_i128 / 6_i128, 7_i128);
  EXPECT_EQ(7_i128 / 2_i128, 3_i128);
  EXPECT_EQ(-7_i128 / 2_i128, -3_i128);
  EXPECT_EQ(7_i128 / -2_i128, -3_i128);
  EXPECT_EQ(-7_i128 / -2_i128, 3_i128);
  EXPECT_EQ(1_i128 / 2_i128, 0_i128);
  EXPECT_EQ(-1_i128 / 2_i128, 0_i128);
  EXPECT_EQ(I128_MIN / 1_i128, I128_MIN);
  EXPECT_EQ(I128_MIN / I128_MIN, 1_i128);
  EXPECT_EQ(I128_MAX / I128_MIN, 0_i128);
  EXPECT_EQ(I128_MIN / 2_i128, -85070591730234615865843651857942052864_i128);
  EXPECT_EQ(
    100000000000000000000000000000000000000_i128 / 10000000000000000000_i128,
    10000000000000000000_i128);
  EXPECT_EQ(
    -100000000000000000000000000000000000000_i128 / 10000000000000000000_i128,
    -10000000000000000000_i128);
  EXPECT_EQ(-123456789012345678901234567890_i128 / 987654321_i128, -124999998873437499901_i128);

  // Unsigned
  EXPECT_EQ(U128_MAX / 1_u128, U128_MAX);
  EXPECT_EQ(U128_MAX / U128_MAX, 1_u128);
  EXPECT_EQ(U128_MAX / 3_u128, 0x5555'5555'5555'5555'5555'5555'5555'5555_u128);
  EXPECT_EQ(U128_MAX / 10_u128, 34028236692093846346337460743176821145_u128);
  EXPECT_EQ(U128_MAX / TWO_64, U64_MAX);
  EXPECT_EQ(100000000000000000000000000000000000000_u128 / 7_u128, 14285714285714285714285714285714285714_u128);
  EXPECT_EQ(U64_MAX / TWO_64, 0_u128);
  // Both operands wider than 64 bits
  EXPECT_EQ(
    0x8000'0000'0000'0000'0000'0000'0000'0005_u128 / 0x1'0000'0000'0000'0001_u128,
    0x7FFF'FFFF'FFFF'FFFF_u128);

  // Compound
  i128 a = -3000000000000000000000_i128;
  a /= 1000000000000000000000_i128;
  EXPECT_EQ(a, -3_i128);
  u128 b = U128_MAX;
  b /= TWO_64;
  EXPECT_EQ(b, U64_MAX);
}

TEST(int128, opMod) {
  // Signed, the sign follows the dividend
  EXPECT_EQ(42_i128 % 6_i128, 0_i128);
  EXPECT_EQ(7_i128 % 2_i128, 1_i128);
  EXPECT_EQ(-7_i128 % 2_i128, -1_i128);
  EXPECT_EQ(7_i128 % -2_i128, 1_i128);
  EXPECT_EQ(-7_i128 % -2_i128, -1_i128);
  EXPECT_EQ(I128_MAX % 10_i128, 7_i128);
  EXPECT_EQ(I128_MIN % 10_i128, -8_i128);
  EXPECT_EQ(I128_MAX % I128_MIN, I128_MAX);
  EXPECT_EQ(-123456789012345678901234567890_i128 % 987654321_i128, -574845669_i128);

  // Unsigned
  EXPECT_EQ(U128_MAX % 10_u128, 5_u128);
  EXPECT_EQ(U128_MAX % 3_u128, 0_u128);
  EXPECT_EQ(U128_MAX % TWO_64, U64_MAX);
  EXPECT_EQ(U128_MAX % U128_MAX, 0_u128);
  EXPECT_EQ(100000000000000000000000000000000000000_u128 % 7_u128, 2_u128);
  EXPECT_EQ(U64_MAX % TWO_64, U64_MAX);
  // Both operands wider than 64 bits
  EXPECT_EQ(
    0x8000'0000'0000'0000'0000'0000'0000'0005_u128 % 0x1'0000'0000'0000'0001_u128,
    0x8000'0000'0000'0006_u128);

  // Division and remainder are consistent
  const i128 n = -123456789012345678901234567890_i128;
  const i128 d = 987654321_i128;
  EXPECT_EQ(n / d * d + n % d, n);
  const u128 un = PATTERN;
  const u128 ud = 0x1234'5678'9ABC'DEF0'1_u128;
  EXPECT_EQ(un / ud * ud + un % ud, un);

  // Compound
  i128 a = -17_i128;
  a %= 5_i128;
  EXPECT_EQ(a, -2_i128);
  u128 b = U128_MAX;
  b %= 1000_u128;
  EXPECT_EQ(b, 455_u128);
}

TEST(int128, opShl) {
  // Unsigned
  EXPECT_EQ(1_u128 << 0, 1_u128);
  EXPECT_EQ(1_u128 << 1, 2_u128);
  EXPECT_EQ(1_u128 << 63, 0x8000'0000'0000'0000_u128);
  EXPECT_EQ(1_u128 << 64, TWO_64);
  EXPECT_EQ(1_u128 << 127, 0x8000'0000'0000'0000'0000'0000'0000'0000_u128);
  EXPECT_EQ(U64_MAX << 4, 0xF'FFFF'FFFF'FFFF'FFF0_u128);
  EXPECT_EQ(U64_MAX << 64, 0xFFFF'FFFF'FFFF'FFFF'0000'0000'0000'0000_u128);
  EXPECT_EQ(PATTERN << 4, 0x1234'5678'9ABC'DEFF'EDCB'A987'6543'2100_u128);
  EXPECT_EQ(PATTERN << 68, 0xEDCB'A987'6543'2100'0000'0000'0000'0000_u128);
  // Bits shifted out are lost
  EXPECT_EQ(U128_MAX << 127, 0x8000'0000'0000'0000'0000'0000'0000'0000_u128);

  // Signed
  EXPECT_EQ(1_i128 << 64, 18446744073709551616_i128);
  EXPECT_EQ(1_i128 << 126, 85070591730234615865843651857942052864_i128);
  EXPECT_EQ(1_i128 << 127, I128_MIN);
  EXPECT_EQ(-1_i128 << 1, -2_i128);
  EXPECT_EQ(-1_i128 << 64, -18446744073709551616_i128);
  EXPECT_EQ(-1_i128 << 127, I128_MIN);
  EXPECT_EQ(-3_i128 << 10, -3072_i128);

  // Compound
  u128 a = 1_u128;
  a <<= 100;
  EXPECT_EQ(a, 0x10'0000'0000'0000'0000'0000'0000_u128);
  i128 b = -5_i128;
  b <<= 70;
  EXPECT_EQ(b, -5_i128 * i128(TWO_64) * 64_i128);
}

TEST(int128, opShr) {
  // Unsigned, logical
  EXPECT_EQ(1_u128 >> 0, 1_u128);
  EXPECT_EQ(1_u128 >> 1, 0_u128);
  EXPECT_EQ(TWO_64 >> 1, 0x8000'0000'0000'0000_u128);
  EXPECT_EQ(TWO_64 >> 64, 1_u128);
  EXPECT_EQ(U128_MAX >> 64, U64_MAX);
  EXPECT_EQ(U128_MAX >> 127, 1_u128);
  EXPECT_EQ(U128_MAX >> 1, u128(I128_MAX));
  EXPECT_EQ(PATTERN >> 4, 0x0012'3456'789A'BCDE'FFED'CBA9'8765'4321_u128);
  EXPECT_EQ(PATTERN >> 68, 0x0012'3456'789A'BCDE_u128);

  // Signed, arithmetic for negative values
  EXPECT_EQ(I128_MAX >> 126, 1_i128);
  EXPECT_EQ(I128_MAX >> 127, 0_i128);
  EXPECT_EQ(-1_i128 >> 1, -1_i128);
  EXPECT_EQ(-1_i128 >> 100, -1_i128);
  EXPECT_EQ(-1_i128 >> 127, -1_i128);
  EXPECT_EQ(I128_MIN >> 127, -1_i128);
  EXPECT_EQ(I128_MIN >> 64, -9223372036854775808_i128);
  EXPECT_EQ(-256_i128 >> 4, -16_i128);
  EXPECT_EQ(-257_i128 >> 4, -17_i128); // Rounds toward negative infinity
  EXPECT_EQ(-18446744073709551616_i128 >> 64, -1_i128);
  EXPECT_EQ(-18446744073709551616_i128 >> 1, -9223372036854775808_i128);

  // Compound
  u128 a = U128_MAX;
  a >>= 100;
  EXPECT_EQ(a, 0xFFF'FFFF_u128);
  i128 b = -1000000000000000000000_i128;
  b >>= 3;
  EXPECT_EQ(b, -125000000000000000000_i128);
}

TEST(int128, opShlShrRoundtrip) {
  for (i32 i = 0; i < 128; ++i) {
    const u128 bit = 1_u128 << i;
    EXPECT_EQ(bit >> i, 1_u128) << "i = " << i;
    EXPECT_EQ((U128_MAX >> i) << i, U128_MAX - (bit - 1_u128)) << "i = " << i;
  }
}

